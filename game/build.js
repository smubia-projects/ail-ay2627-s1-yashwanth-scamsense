// Vercel build step: inject the Cloud Run API base URL into config.js (gitignored, generated at build time).
const fs = require("fs");
const path = require("path");

const apiBase = (process.env.VITE_API_BASE || "http://localhost:8080").replace(/\/+$/, "");
fs.writeFileSync(
  path.join(__dirname, "config.js"),
  `// Auto-generated by build.js - do not edit\nwindow.VITE_API_BASE = ${JSON.stringify(apiBase)};\n`
);
console.log(`Generated config.js with VITE_API_BASE: ${apiBase}`);
